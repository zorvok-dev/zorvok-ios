package adapter

import (
	"os"
	"path/filepath"
	"testing"
)

func writeExecutable(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o755); err != nil {
		t.Fatal(err)
	}
}

func TestResolveFromPodScript_DirectRubyShebang(t *testing.T) {
	// The `gem install cocoapods` shape: no GEM_HOME indirection needed.
	dir := t.TempDir()
	pod := filepath.Join(dir, "pod")
	writeExecutable(t, pod, "#!/usr/bin/ruby\n# generated by RubyGems\n")

	env, err := resolveFromPodScript(pod)
	if err != nil {
		t.Fatal(err)
	}
	if env.RubyPath != "/usr/bin/ruby" {
		t.Errorf("RubyPath = %q, want /usr/bin/ruby", env.RubyPath)
	}
	if env.GemHome != "" {
		t.Errorf("GemHome = %q, want empty", env.GemHome)
	}
}

func TestResolveFromPodScript_HomebrewWrapper(t *testing.T) {
	dir := t.TempDir()
	realPod := filepath.Join(dir, "libexec", "bin", "pod")
	if err := os.MkdirAll(filepath.Dir(realPod), 0o755); err != nil {
		t.Fatal(err)
	}
	writeExecutable(t, realPod, "#!/opt/homebrew/opt/ruby/bin/ruby\n# generated by RubyGems\n")

	wrapper := filepath.Join(dir, "pod")
	writeExecutable(t, wrapper, "#!/bin/bash\nGEM_HOME=\""+dir+"/libexec\" exec \""+realPod+"\" \"$@\"\n")

	env, err := resolveFromPodScript(wrapper)
	if err != nil {
		t.Fatal(err)
	}
	if env.RubyPath != "/opt/homebrew/opt/ruby/bin/ruby" {
		t.Errorf("RubyPath = %q, want /opt/homebrew/opt/ruby/bin/ruby", env.RubyPath)
	}
	if env.GemHome != dir+"/libexec" {
		t.Errorf("GemHome = %q, want %q", env.GemHome, dir+"/libexec")
	}
}

func TestResolveFromPodScript_UnrecognizedWrapperFallsBackGracefully(t *testing.T) {
	dir := t.TempDir()
	pod := filepath.Join(dir, "pod")
	writeExecutable(t, pod, "#!/bin/bash\necho 'something unexpected'\n")

	env, err := resolveFromPodScript(pod)
	if err != nil {
		t.Fatal(err)
	}
	if env.RubyPath != "ruby" {
		t.Errorf("expected a best-effort fallback to plain `ruby`, got %q", env.RubyPath)
	}
}

func TestResolveFromPodScript_MissingFileFallsBackGracefully(t *testing.T) {
	env, err := resolveFromPodScript(filepath.Join(t.TempDir(), "does-not-exist"))
	if err != nil {
		t.Fatal(err)
	}
	if env.RubyPath != "ruby" {
		t.Errorf("expected fallback, got %q", env.RubyPath)
	}
}
